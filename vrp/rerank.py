"""Stage-2 relational reordering header (intra-pair reordering).

motivation
----
Stage-1 (`VRPCatModel`) given z_ij ∈ R^K, **per-pair constant translation**
(e.g. α·LSE, temperature scaling) Identity for argmax / order within pair - mathematically impossible to change
Top-1 and R@k within the pair. To actually change the ordering within a pair, the modifier must be **predicate-wise**:

    s’_ij[k] = z_ij[k] + Δ_ij[k], Δ dependence (pair, k) interaction

This module provides two types of Δ:

* `calib` - parameterless a priori calibration: Δ_k = -τ·log π_k (π = training set predicate frequency).
  It differs predicate by predicate, so it can change the order within the pair; its essence is long-tail logit adjustment
  (Menon et al., ICLR 2021). As an **interpretable control**, prove that the gain does not come from the frequency prior.

* `learn`——Learning residual header: ”pair visual/geometric features × predicate text embedding × Stage-1 score”
  Do the interaction and output the bounded residual Δ = γ·tanh(f(·)). The training goal is cross entropy on the candidate set
  (Candidate = Stage-1 top-M ∪ GT), Stage-1 is frozen throughout (two-stage reordering).

design constraints
--------
1. **Must not degenerate into a constant**: Δ must be generated by pair×predicate interaction; the structural guarantee is
   The input to `head` contains `fp * ft` (the element-wise product of pair features and predicate embeddings).
2. **Bounded**: Δ = γ·tanh(·), γ initial value is 2.0 (log domain), avoid using Stage-1
   Predicates other than top-M are accidentally added; at the same time, it is guaranteed that the mask predicate (-1e9) will not be turned out.
3. **Do not change Stage-1**: reranker only reads the log scores and features output by Stage-1,
   No back-transmission or fine-tuning, making it easy to compare side-by-side with any baseline.
"""
from __future__ import annotations

from typing import List, Optional, Sequence, Tuple

import torch
import torch.nn as nn
import torch.nn.functional as F


class RelReranker(nn.Module):
    """pair×predicate interactive residual reordering header.

    Enter (by batch):
        z_top (B, M) top-M value of Stage-1 score (log domain)
        v_s/v_o (B, 512) Subject/Object ROI visual features
        s_s/s_o (B, 8) subject/object geometric features
        txt_top (B, M, d_t) corresponds to the text embedding of the predicate
    Output:
        Δ (B, M) bounded residual, added directly to z_top
    """

    def __init__(self, d_v: int = 512, d_t: int = 512, d: int = 192,
                 gamma_init: float = 2.0, use_rev: bool = True):
        super().__init__()
        self.use_rev = use_rev
        d_pair = d_v * 4 + 24          # [v_s, v_o, v_s-v_o, v_s*v_o, s_s, s_o, s_s-s_o]
        self.pair_enc = nn.Sequential(
            nn.Linear(d_pair, d), nn.GELU(), nn.LayerNorm(d),
            nn.Linear(d, d), nn.GELU(),
        )
        self.pred_enc = nn.Sequential(nn.Linear(d_t, d), nn.GELU())
        # Extra 2 dimensions: log score of the inverse predicate in the opposite direction (o,s) + whether the inverse exists (mask)
        self.head = nn.Sequential(
            nn.Linear(d * 3 + (3 if use_rev else 1), d), nn.GELU(), nn.Linear(d, 1),
        )
        self.gamma = nn.Parameter(torch.tensor(float(gamma_init)))

    def forward(self, z_top: torch.Tensor, v_s: torch.Tensor, v_o: torch.Tensor,
                s_s: torch.Tensor, s_o: torch.Tensor,
                txt_top: torch.Tensor,
                z_rev: Optional[torch.Tensor] = None,
                has_inv: Optional[torch.Tensor] = None) -> torch.Tensor:
        pf = torch.cat([v_s, v_o, v_s - v_o, v_s * v_o,
                        s_s, s_o, s_s - s_o], dim=-1)
        fp = self.pair_enc(pf).unsqueeze(1)                  # (B,1,d)
        ft = self.pred_enc(txt_top)                           # (B,M,d)
        parts = [fp.expand(-1, ft.size(1), -1), ft, fp * ft, z_top.unsqueeze(-1)]
        if self.use_rev:
            if z_rev is None:
                z_rev = torch.zeros_like(z_top)
                has_inv = torch.zeros_like(z_top)
            parts += [z_rev.unsqueeze(-1), has_inv.unsqueeze(-1)]
        h = torch.cat(parts, dim=-1)
        return self.gamma * torch.tanh(self.head(h).squeeze(-1))


# ----------------------------------------------------------------------
def to_log_scores(scores: torch.Tensor) -> torch.Tensor:
    """Unify the scoring into the **log domain** (reordering headers and adding residuals are all performed in the log domain).

    Both upstream calibers have to be processed:
      * `SCORE_LOGITS=True` (default) → scores are logits, do `log_softmax`.
        It is a per-pair constant translation that does not change the order within the pair, but can make the numerical dimension of z_top
        Consistent with the log probability, the scales of the residuals γ·tanh are comparable.
      * `SCORE_LOGITS=False` (historical caliber) → The score is the softmax probability, which is directly taken as log.

    The mask predicate is set to -1e9, and in the probability caliber it is -20.7 after clamping, which is still more than 10 orders of magnitude higher than the normal term.
    Gap; residuals |Δ| ≤ γ, not flipped.
    """
    import vrp.model as _vm
    if getattr(_vm, "SCORE_LOGITS", False):
        return torch.log_softmax(scores, dim=-1)
    return torch.log(scores.clamp_min(1e-9))


def pair_row(a: torch.Tensor, b: torch.Tensor, n: int) -> torch.Tensor:
    """predcls Line numbers of candidate pairs (order: `for a: for b: b!=a`).

    Same origin as `_pair_index`, but purely vectorized to avoid building dict for inverse lookup (o,s).
    """
    return a * (n - 1) + torch.where(b < a, b, b - 1)


def rev_feature(z_mat: torch.Tensor, jr: Optional[int], cand_idx: torch.Tensor,
                inv_of: Optional[torch.Tensor]):
    """Take the log score of the ”inverse predicate in the opposite direction (o,s)” for the candidate predicate.

    Return (z_rev (M,), has_inv (M,)). When there is no inverse predicate or no inversion pair, the corresponding position is 0 and mask=0,
    This allows the model to explicitly learn ”this piece of information is missing” instead of being misled by the 0 value.
    """
    M = cand_idx.numel()
    z_rev = torch.zeros(M, device=z_mat.device, dtype=z_mat.dtype)
    has = torch.zeros(M, device=z_mat.device, dtype=z_mat.dtype)
    if jr is None or inv_of is None or inv_of.numel() <= 1:
        return z_rev, has
    inv_of = inv_of.to(z_mat.device)
    rv = inv_of[cand_idx + 1] - 1                     # 0-based inverse predicate, -1 means none
    ok = rv >= 0
    if ok.any():
        z_rev[ok] = z_mat[int(jr), rv[ok]]
        has[ok] = 1.0
    return z_rev, has


def rev_feature_batch(z: torch.Tensor, a_idx: torch.Tensor, b_idx: torch.Tensor,
                      n: int, cand_idx: torch.Tensor,
                      inv_of: Optional[torch.Tensor]):
    """Batch version of `rev_feature`: z (P,K), cand_idx (P,M) → (z_rev (P,M), has (P,M))."""
    P, M = cand_idx.shape
    if inv_of is None or inv_of.numel() <= 1:
        return torch.zeros(P, M, device=z.device, dtype=z.dtype), \
               torch.zeros(P, M, device=z.device, dtype=z.dtype)
    inv_of = inv_of.to(z.device)
    rv = inv_of[cand_idx + 1] - 1                     # (P,M)
    ok = rv >= 0
    # Reverse line number: index of (b,a)
    jr = pair_row(b_idx, a_idx, n)                    # (P,)
    src = z[jr.unsqueeze(1).expand(-1, M), rv.clamp_min(0)]   # (P,M)
    z_rev = torch.where(ok, src, torch.zeros_like(src))
    return z_rev, ok.to(z.dtype)


def make_candidates(z: torch.Tensor, gt: Sequence[Tuple[int, int, int]],
                    pair_pos: dict, m_top: int):
    """Construct a candidate set for reranker training/inference: Stage-1 top-M ∪ GT predicate.

    Return:
        top_idx (M,) long candidate predicate index (replaces the last position when GT is not in top-M)
        z_top (M,) float Stage-1 log score on candidate
        gt_pos int GT’s position in the candidate (useless during inference)
    """
    M = min(m_top, z.numel())
    z_top, top_idx = torch.topk(z, M, dim=-1)
    top_idx = top_idx.clone()
    gt_pos = -1
    for (s, o, p) in gt:
        if pair_pos.get((s, o)) is None:
            continue
        if (top_idx == p).any():
            gt_pos = int((top_idx == p).nonzero()[0, 0])
        else:
            top_idx[-1] = p
            z_top[-1] = z[p]
            gt_pos = M - 1
        break
    return top_idx, z_top, gt_pos


@torch.no_grad()
def collect_rerank_data(model, obj_emb, data, m_top: int = 20,
                        keep_pair=None, log=print, inv_of=None) -> dict:
    """Collect on train split (pair index, candidate predicate, Stage-1 score, GT position, inverse pair score).

    `keep_pair(i, s, o) -> bool` can be used to set aside the verification graph (to avoid reranker training/evaluation on the same graph).
    `inv_of` (K+1,) long: Inverse predicate table (0-based, -1=no inverse), used to construct (o,s) direction features.
    """
    img_idx, sidx, oidx, cand, zs, gts = [], [], [], [], [], []
    zrevs, hass = [], []
    n_img = len(data.ids)
    for i in range(n_img):
        gt = data.rels[i]
        if not gt:
            continue
        scores, pairs = _score_image_nb(model, obj_emb, data, i)
        if scores is None:
            continue
        z = to_log_scores(scores)
        pair_pos = {p: k for k, p in enumerate(pairs)}
        for (s, o, p) in gt:
            j = pair_pos.get((s, o))
            if j is None:
                continue
            if keep_pair is not None and not keep_pair(i, s, o):
                continue
            top_idx, z_top, gt_pos = make_candidates(z[j], [(s, o, p)], pair_pos, m_top)
            if gt_pos < 0:
                continue
            zr, hv = rev_feature(z, pair_pos.get((o, s)), top_idx, inv_of)
            img_idx.append(i); sidx.append(s); oidx.append(o)
            cand.append(top_idx); zs.append(z_top); gts.append(gt_pos)
            zrevs.append(zr); hass.append(hv)
    if not img_idx:
        return {}
    out = {
        "img": torch.tensor(img_idx, dtype=torch.long),
        "s": torch.tensor(sidx, dtype=torch.long),
        "o": torch.tensor(oidx, dtype=torch.long),
        "cand": torch.stack(cand),
        "z": torch.stack(zs),
        "gt": torch.tensor(gts, dtype=torch.long),
        "zrev": torch.stack(zrevs),
        "has": torch.stack(hass),
    }
    log(f"  [rerank] Collect {len(img_idx):,} a GT pair (candidate top-{m_top} ∪ GT）；"
        f"Inverse pair availability {float(out['has'].mean()):.4f}")
    return out


def _score_image_nb(model, obj_emb, data, i: int):
    """Native implementation of bitwise synonym for `_score_image` (predcls caliber).

    Deliberately **not** import from `tools.small_sample_experiment`: this script often starts with `__main__`
    Run, repeated import will perform module-level initialization twice (global switches such as SCORE_LOGITS appear twice).
    """
    dev = next(model.parameters()).device
    n = data.n_obj[i]
    pairs = [(a, b) for a in range(n) for b in range(n) if a != b]
    if not pairs:
        return None, []
    S = torch.tensor([p[0] for p in pairs], dtype=torch.long, device=dev).unsqueeze(0)
    O = torch.tensor([p[1] for p in pairs], dtype=torch.long, device=dev).unsqueeze(0)
    xt = obj_emb(data.t[i].unsqueeze(0).to(dev)) if obj_emb is not None else \
        data.t[i].unsqueeze(0).to(dev)
    x = {"v": data.v[i].unsqueeze(0).to(dev),
         "t": xt,
         "s": data.s[i].unsqueeze(0).to(dev)}
    masks = data.masks[i].unsqueeze(0).to(dev)
    p_ij, _ = model.forward_inference(x, masks, S, O)
    return p_ij[0], pairs


def train_reranker(head: RelReranker, pack: dict, data, txt: torch.Tensor,
                   epochs: int = 8, lr: float = 2e-3, batch: int = 4096,
                   log=print) -> dict:
    """Train the reranker (candidate set cross-entropy) on frozen Stage-1 acquisition data."""
    dev = next(head.parameters()).device
    txt = txt.to(dev)
    n = pack["img"].numel()
    if n == 0:
        return {"n": 0}
    opt = torch.optim.AdamW(head.parameters(), lr=lr, weight_decay=1e-4)
    img, sidx, oidx = pack["img"].to(dev), pack["s"].to(dev), pack["o"].to(dev)
    cand, z, gt = pack["cand"].to(dev), pack["z"].to(dev), pack["gt"].to(dev)
    zrv = pack["zrev"].to(dev) if pack.get("zrev") is not None else None
    hasv = pack["has"].to(dev) if pack.get("has") is not None else None

    # Flatten the v/s of each picture into a large table in advance, and linearly index by (img,obj) to avoid taking the list batch by batch
    v_all = torch.cat([data.v[i] for i in range(len(data.ids))], 0).to(dev)
    s_all = torch.cat([data.s[i] for i in range(len(data.ids))], 0).to(dev)
    off = torch.tensor([0] + [data.v[i].shape[0] for i in range(len(data.ids))],
                       dtype=torch.long, device=dev).cumsum(0)

    head.train()
    hist = []
    for ep in range(epochs):
        perm = torch.randperm(n, device=dev)
        tot = cor = 0
        lsum = 0.0
        for b in range(0, n, batch):
            sel = perm[b:b + batch]
            gi, gs, go = img[sel], sidx[sel], oidx[sel]
            zz, cc, gg = z[sel], cand[sel], gt[sel]
            delta = head(zz, v_all[off[gi] + gs], v_all[off[gi] + go],
                         s_all[off[gi] + gs], s_all[off[gi] + go],
                         txt[cc],
                         zrv[sel] if zrv is not None else None,
                         hasv[sel] if hasv is not None else None)
            loss = F.cross_entropy(zz + delta, gg)
            opt.zero_grad(); loss.backward()
            torch.nn.utils.clip_grad_norm_(head.parameters(), 1.0)
            opt.step()
            lsum += float(loss) * gi.numel()
            tot += gi.numel()
            cor += int(((zz + delta).argmax(-1) == gg).sum())
        hist.append({"ep": ep + 1, "loss": lsum / max(tot, 1),
                     "top1": cor / max(tot, 1)})
        log(f"  [rerank] ep{ep+1}/{epochs} loss={hist[-1]['loss']:.4f} "
            f"acc={hist[-1]['top1']:.4f}")
    head.eval()
    return {"n": n, "hist": hist}


@torch.no_grad()
def rerank_inplace(head: RelReranker, scores: torch.Tensor, data, i: int,
                   m_top: int, txt: torch.Tensor,
                   inv_of: Optional[torch.Tensor] = None) -> torch.Tensor:
    """Add the reranker residual back to the (P,K) score of the i-th graph (top-M positions only).

    The order of candidate pairs must be consistent with `_score_image` (predcls: `for a: for b: a!=b`),
    Otherwise, the residual will be added to the wrong pair - here we reverse the solution by row number and do a consistency check.
    `inv_of`: (K+1,) long inverse predicate table for (o,s) direction features.
    """
    z = to_log_scores(scores)
    P, K = z.shape
    M = min(m_top, K)
    z_top, top_idx = torch.topk(z, M, dim=-1)                 # (P,M)
    a_idx, b_idx = _pair_index(data.n_obj[i], P, z.device)
    if a_idx is None:
        return scores
    v = data.v[i].to(z.device); s = data.s[i].to(z.device)
    zr, hv = rev_feature_batch(z, a_idx, b_idx, data.n_obj[i], top_idx, inv_of)
    delta = head(z_top, v[a_idx], v[b_idx], s[a_idx], s[b_idx], txt[top_idx], zr, hv)
    z.scatter_add_(-1, top_idx, delta)
    return z


_PAIR_CACHE: dict = {}


def _flat_vs(data, dev):
    """Flatten image-by-image v/s into a large table + offset table to facilitate linear indexing by (img, obj)."""
    n_img = len(data.ids)
    v_all = torch.cat([data.v[i] for i in range(n_img)], 0).to(dev)
    s_all = torch.cat([data.s[i] for i in range(n_img)], 0).to(dev)
    off = torch.tensor([0] + [data.v[i].shape[0] for i in range(n_img)],
                       dtype=torch.long, device=dev).cumsum(0)
    return v_all, s_all, off


@torch.no_grad()
def eval_reranker_pack(head: RelReranker, pack: dict, data, txt: torch.Tensor,
                       dev, batch: int = 8192) -> dict:
    """Compare Stage-1 and top1 after reordering on the set, and count the **order change rate**.

    `flip` = Reorder to change the sample proportion of argmax - directly answer ”Is this module real?”
    Changed the ordering within the pair” (the flip of a per-pair constant translation is always 0).
    """
    if not pack or pack["img"].numel() == 0:
        return {"base": 0.0, "rerank": 0.0, "flip": 0.0, "n": 0}
    head.eval()
    txt = txt.to(dev)
    v_all, s_all, off = _flat_vs(data, dev)
    img, sidx, oidx = pack["img"].to(dev), pack["s"].to(dev), pack["o"].to(dev)
    cand, z, gt = pack["cand"].to(dev), pack["z"].to(dev), pack["gt"].to(dev)
    zrv = pack["zrev"].to(dev) if pack.get("zrev") is not None else None
    hasv = pack["has"].to(dev) if pack.get("has") is not None else None
    tot = base = rr = fl = 0
    for b in range(0, img.numel(), batch):
        sl = slice(b, b + batch)
        gi = img[sl]
        delta = head(z[sl], v_all[off[gi] + sidx[sl]], v_all[off[gi] + oidx[sl]],
                     s_all[off[gi] + sidx[sl]], s_all[off[gi] + oidx[sl]],
                     txt[cand[sl]],
                     zrv[sl] if zrv is not None else None,
                     hasv[sl] if hasv is not None else None)
        zz = z[sl]
        p0 = zz.argmax(-1)
        p1 = (zz + delta).argmax(-1)
        tot += gi.numel()
        base += int((p0 == gt[sl]).sum())
        rr += int((p1 == gt[sl]).sum())
        fl += int((p0 != p1).sum())
    return {"base": base / max(tot, 1), "rerank": rr / max(tot, 1),
            "flip": fl / max(tot, 1), "n": tot}

def _pair_index(n: int, P: int, dev):
    """The cached (a,b) index is bit-by-bit consistent with the predcls candidate pair generation order."""
    key = (n, P)
    if key in _PAIR_CACHE:
        a, b = _PAIR_CACHE[key]
        return a.to(dev), b.to(dev)
    a = [x for x in range(n) for y in range(n) if y != x]
    b = [y for x in range(n) for y in range(n) if y != x]
    if len(a) != P:                                           # Caliber does not match (such as gtpairs)
        return None, None
    ta = torch.tensor(a, dtype=torch.long)
    tb = torch.tensor(b, dtype=torch.long)
    _PAIR_CACHE[key] = (ta, tb)
    return ta.to(dev), tb.to(dev)
