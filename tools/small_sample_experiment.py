def apply_loss_fixes(normalize_maha: bool = True, fix_coh: bool = True) -> dict:
    """Replace the loss function used by vrp.model at runtime (**without modifying the vrp/ source file**).

    Both items are ”scale calibration”, which is applied uniformly to all arms, so it does not destroy the fair comparison between arms:

    (1) fix_coh: vrp/losses.py’s coh_loss does not do softmax on the Head_1 output, but does L1
        Normalization; Head_1 output normalized division by near zero when output contains negative values → Illegal ”probability” (contains negative/explosion),
        The measured L_coh=8.9e11, dominates and destroys the classification branch. Add softmax here (restore simplex).

    (2) normalize_maha: ||Δ||²_{G^{-1}} of equation (9) grows linearly with dimension d (when d=256
        L_inv≈4.7e2 vs L_cls≈5.5, gradient 9.8e3 vs 2.2e1) → classification branches are overwhelmed. here
        The Mahalanobis terms are averaged along dimensions (divided by d) to make the loss terms comparable in magnitude.
        The representation terms of Equation (23) are treated in the same way, and the distribution term (D_JS) remains unchanged.
    """
    import vrp.model as vrp_model
    from vrp.losses import js_divergence

    info = {}
    if fix_coh:
        def coh_loss_fixed(f_r1, f_r2, P_bar_sq, head1, head2):
            # ⚠️ 2026-10-18: Consistent with coh_loss of vrp/losses.py
            # (diag is weighted in **log space**, see the description of this function).
            # Note: This patch is now **redundant** (losses.py has already fixed softmax),
            # Reserved only to not change the existing calibration process.
            diag_p = torch.diagonal(P_bar_sq)
            log_diag = torch.log(diag_p.clamp(min=1e-12))
            a = torch.softmax(head1(f_r1) + log_diag.unsqueeze(-2), dim=-1)
            b = torch.softmax(head2(f_r2), dim=-1)
            return js_divergence(a, b).mean()
        vrp_model.coh_loss = coh_loss_fixed
        info["coh_fix"] = True

    if normalize_maha:
        def inv_loss_fixed(r_exp, r_imp, G_inv):
            delta = r_exp - r_imp
            maha = torch.einsum("...i,ij,...j->...", delta, G_inv, delta)
            return maha.mean() / delta.shape[-1]
        vrp_model.inv_loss = inv_loss_fixed

        def dag_loss_fixed(p_ij, p_ji_swap, r_ji, Inv_p_ij, c_dag, G_inv, w_i, shared,
                           lambda_dag=1.0):
            l_dist = js_divergence(p_ji_swap, Inv_p_ij)
            c_expected = torch.einsum("...k,kd->...d", p_ij, c_dag)
            diff = shared(r_ji) - c_expected
            l_repr = torch.einsum("...i,ij,...j->...", diff, G_inv, diff) / diff.shape[-1]
            per = w_i * (lambda_dag * l_dist + l_repr)
            return per.mean(), l_dist.mean(), l_repr.mean()
        vrp_model.dag_loss = dag_loss_fixed
        info["maha_norm"] = True
    return info


