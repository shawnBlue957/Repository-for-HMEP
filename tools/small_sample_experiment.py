# Block results are reused (default cache directory) to avoid recalculation in each epoch.
# ⚠️ Semantic boundary: shuffling within blocks + shuffling block order every epoch ⟹ Global randomness is slightly weaker than full shuffle,
# But each epoch still sees all samples once; the paper needs to indicate ”block assembly” in the experimental settings.
