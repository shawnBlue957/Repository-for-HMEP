class ImageZip:
    """Read VG images by name (extract only the required members, do not decompress the entire image).

    ⚠️ **Tolerate missing zip** (Fixed in 2026-10-18): `get_image_reader` before **entering feature branch**
    This object is constructed, and `__init__` will immediately `zipfile.ZipFile(p)` open the file⟹ even if ROI/CLIP
    The feature cache has been hit (no need to read the original image at all), and it will crash directly because the source zip does not exist:
        FileNotFoundError: .../data/raw/vg_images/images.zip
    (The actual measurement resulted in the failure of all roi_vg_ours / roi_vg_abl of all tasks.)

    Therefore, it is changed to: Missing zip **skip and alert**, and None will be silently returned only when **really needs to read pixels**.
    Cache hit paths are not affected.
    """

    def __init__(self, paths: Sequence[str], strict: bool = False):
        self.zips = []
        self.missing: List[str] = []
        for p in paths:
            if not p or not os.path.exists(p):
                self.missing.append(p)
                continue
            try:
                self.zips.append(zipfile.ZipFile(p))
            except Exception as e:                      # corrupted/non-zip
                self.missing.append(f"{p} ({e})")
        if self.missing:
            msg = (f"ImageZip: {len(self.missing)} sources zip Not available, skipped:"
                   f"{[os.path.basename(m) for m in self.missing]}")
            if strict:
                raise FileNotFoundError(msg)
            # Non-strict: only alerts. There is no need to read pixels when the feature cache hits; read() returns None when it misses.
            # The upstream will count the number of lost images and run as usual (no error results will be silently produced).
            print(f"  ⚠️ {msg}", flush=True)
        self.index: Dict[str, Tuple[int, str]] = {}
        for zi, z in enumerate(self.zips):
            for name in z.namelist():
                if name.lower().endswith((".jpg", ".jpeg")):
                    base = os.path.basename(name)
                    stem = os.path.splitext(base)[0]
                    self.index.setdefault(stem, (zi, name))

    def read(self, image_id) -> Optional[bytes]:
        hit = self.index.get(str(image_id))
        if hit is None:
            return None
        zi, name = hit
        try:
            return self.zips[zi].read(name)
        except Exception:
            return None


def geom_features(box, w, h) -> np.ndarray:
    x1, y1, x2, y2 = [float(v) for v in box]
    bw, bh = max(x2 - x1, 1e-3), max(y2 - y1, 1e-3)
    cx, cy = (x1 + x2) / 2.0, (y1 + y2) / 2.0
    W, H = max(float(w), 1.0), max(float(h), 1.0)
    ncx, ncy = cx / W, cy / H
    nw, nh = bw / W, bh / H
    area = nw * nh
    aspect = float(np.clip(bw / bh, 0.1, 10.0)) / 10.0
    # Signed offset relative to image center (learnable entry for directional polarity; relative displacement of host and object is implemented implicitly by the ordered difference of R1)
    return np.array([ncx, ncy, nw, nh, area, aspect, ncx - 0.5, ncy - 0.5], dtype=np.float32)


def extract_features(records: List[dict], cache_path: str, imgzip: ImageZip,
                     log=print) -> Dict[str, dict]:
    if os.path.exists(cache_path):
        t = time.time()
        cache = torch.load(cache_path, weights_only=False)
        log(f"  Load feature cache {os.path.basename(cache_path)}（{len(cache)} Figure,{time.time()-t:.1f}s）")
        return cache

    from clip_cpu import CLIPVisionCPU
    from PIL import Image

    # CLIPVisionCPU automatically selects the device (CUDA is available as GPU). ViT forward under GPU is about 46× faster than CPU.
    enc = CLIPVisionCPU(CLIP_WEIGHTS)
    log(f"  CLIP Vision tower equipment = {enc.device} / {enc.dtype}")

    # ⚠️ Memory design (required for full 84,169 images): the final cache itself is about 2.1 GB
    # (84,169 images × mean 12.3 objects × 512 × 4 B).
    #Earlier versions first accumulate `feats{iid:{j:vec}}` and then transfer `cache{iid:{v:fv}}`,
    # **Two copies reside at the same time ⟹ Peak is about 4.2 GB**, which will cause a lot of paging on this machine (only 4.5 GB of available memory).
    # Now changed to **fill `cache`** directly by block, peak value ≈ cache + 1 block clipping ≈ 2.4 GB.
    BLOCK_IMGS = 512
    cache: Dict[str, dict] = {}
    miss_img, miss_crop = 0, 0
    t0 = time.time()
    n_enc = 0
    last_log = t0

    for b0 in range(0, len(records), BLOCK_IMGS):
        block = records[b0:b0 + BLOCK_IMGS]
        crops, keys, entries = [], [], []       # entries: (im, fv, W, H)
        for im in block:
            raw = imgzip.read(im.image_id)
            if raw is None:
                miss_img += 1
                continue
            try:
                pil = Image.open(io.BytesIO(raw)).convert("RGB")
            except Exception:
                miss_img += 1
                continue
            W, H = pil.size
            fv = torch.zeros(len(im.labels), FEAT_DIM)
            ei = len(entries)
            for j, box in enumerate(im.boxes):
                x1, y1, x2, y2 = box
                x1, y1 = max(0, min(int(x1), W - 1)), max(0, min(int(y1), H - 1))
                x2, y2 = max(x1 + 1, min(int(x2), W)), max(y1 + 1, min(int(y2), H))
                try:
                    crops.append(pil.crop((x1, y1, x2, y2)))
                except Exception:
                    miss_crop += 1
                    continue
                keys.append((ei, j))
            entries.append((im, fv, W, H))
            pil.close()

        if crops:
            f = enc.encode_pils(crops, batch_size=256)
            for (ei, j), vec in zip(keys, f):
                entries[ei][1][j] = vec
            n_enc += len(crops)

        # Only write to the resident cache after the cropping encoding is completed, and then release the temporary object of this block.
        for im, fv, W, H in entries:
            cache[im.image_id] = {"v": fv, "labels": list(im.labels),
                                  "boxes": [list(b) for b in im.boxes], "W": W, "H": H}
        del crops, keys, entries

        if time.time() - last_log > 20:
            done = min(b0 + BLOCK_IMGS, len(records))
            log(f"    Processed {done:,}/{len(records):,} Figure | Encoded {n_enc:,} Crop | "
                f"{n_enc / max(time.time()-t0, 1e-6):.0f} a/s | "
                f"Used {(time.time()-t0)/60:.1f} minutes")

    log(f"  Coding completed:{n_enc:,} cutting, time {(time.time()-t0)/60:.1f} minutes"
        f" (Lost pictures {miss_img}, Lost frame {miss_crop}）")
    torch.save(cache, cache_path)
    log(f"  Feature extraction is completed:{len(cache)} Picture, time {time.time()-t0:.1f}s → {os.path.basename(cache_path)}")
    return cache


def extract_image_features(records: List, imgzip, cache_path: str, log=print):
    """Image-level CLIP features (whole image resized 224) for use in q’s CLIP mode.

    Cache the object clipping features separately from `extract_features`: the clipping cache can be reused.
    But q = softmax(cos(v_img, v_txt)/τ) requires **whole graph** semantics, and the inputs of the two are different.
    """
    import time as _t
    if os.path.exists(cache_path):
        t = _t.time()
        cache = torch.load(cache_path, weights_only=False)
        log(f"  Load image-level feature cache {os.path.basename(cache_path)}"
            f"（{len(cache)} Figure,{_t.time()-t:.1f}s）")
        return cache

    from clip_cpu import CLIPVisionCPU
    from PIL import Image

    enc = CLIPVisionCPU(CLIP_WEIGHTS)
    log(f"  image level CLIP Equipment = {enc.device} / {enc.dtype}")

    # Streaming: Each BLK image is encoded and released immediately after decoding to avoid holding tens of thousands of PILs at one time
    BLK = 512
    cache: Dict[str, torch.Tensor] = {}
    buf, buf_keys = [], []
    t0 = _t.time()

    def _flush_img():
        nonlocal buf, buf_keys
        if not buf:
            return
        f = enc.encode_pils(buf, batch_size=256)
        for k, v in zip(buf_keys, f):
            cache[k] = v
        buf, buf_keys = [], []

    for k, im in enumerate(records):
        raw = imgzip.read(im.image_id)
        if raw is not None:
            try:
                buf.append(Image.open(io.BytesIO(raw)).convert("RGB"))
                buf_keys.append(im.image_id)
            except Exception:
                pass
        if len(buf) >= BLK:
            _flush_img()
            log(f"    The entire image is encoded {len(cache):,}/{len(records):,} | "
                f"{(len(cache)/max(_t.time()-t0,1e-6)):.0f} Zhang/s | "
                f"Used {(_t.time()-t0)/60:.1f} minutes")
    _flush_img()
    torch.save(cache, cache_path)
    log(f"  Image level features are completed:{len(cache)} Zhang, time {(_t.time()-t0)/60:.1f} minutes"
        f" → {os.path.basename(cache_path)}")
    return cache


