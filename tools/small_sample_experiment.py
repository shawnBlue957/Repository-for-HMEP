class FrozenObjText(nn.Module):
    """CLIP object-like text embedding for x_t (replaces nn.Embedding(151,512)).

    Category side entrance of the semantic pathway: `v_txt/v_inv` in the final draft §3.7 corresponds to the predicate side,
    This class provides the object-side frozen text feature. padding_idx=0 (background) is set to zero.
    The table has been reduced by build_semantic_path to model dimension d (frozen orthographic projection).
    """

    def __init__(self, table: torch.Tensor):
        super().__init__()
        self.register_buffer("table", table.float())
        with torch.no_grad():
            self.table[0].zero_()
        self.dim = table.shape[1]

    def forward(self, idx: torch.Tensor) -> torch.Tensor:
        return self.table[idx.long()]

    def parameters(self, recurse: bool = True):
        return iter(())          # Fully frozen, no training parameters


def to_device(batch: dict, dev: torch.device) -> dict:
    """Move a batch (with nested x dictionary) to the target device."""
    out = dict(batch)
    out["x"] = {k: v.to(dev, non_blocking=True) for k, v in batch["x"].items()}
    for k, v in batch.items():
        if k != "x" and torch.is_tensor(v):
            out[k] = v.to(dev, non_blocking=True)
    return out



