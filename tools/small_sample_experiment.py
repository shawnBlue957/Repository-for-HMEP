def load_data_driven_groups(dataset: str):
    """Load inverse predicate group for **Annotation Data Driven** (fixes P0).

    The product is generated by `tools/build_inv_pairs_from_data.py`: only keep the annotations with **reciprocal evidence**
    2-loop (hit rate ≥ min_rate and reciprocity test passed), the remaining predicates are not paired ⟹ Take the φ exit of (17).

    Advantages compared to manual semantic grouping (actual measurement):
      · VRD: Only 5 of the 30 manual groups can stand in the annotation (5 with hits / 25 without hits);
             Data-driven only recognizes 4 pairs (on↔wear, above↔below, behind↔in the front of,
             on the left of↔on the right of), hit rate 11%–45%, and J²=I deviation 0.00e+00.
      · Key: Predicates with unconfirmed inverses no longer degenerate into Inv(r)=r**. Degenerating into a fixed point will allow Equation (23)
        It becomes ”requiring p_ji ≈ p_ij” (forced symmetry), which is inconsistent with the ”93.3% asymmetry” of equation (16);
        Taking the φ exit is the correct semantics of (15) (”This predicate has no inverse in R”).

    Returns [(A, B), ...] (group-to-group form), or None on failure.
    """
    import json as _json
    p = os.path.join(ART, f"inv_pairs_{dataset}.json")
    if not os.path.exists(p):
        return None
    try:
        d = _json.load(open(p, encoding="utf-8"))
    except Exception:
        return None
    cycles = d.get("cycles") or []
    groups = [([a], [b]) for a, b in cycles]
    n_inv = 2 * len(cycles)
    K = len(d.get("predicates") or []) or (n_inv + len(d.get("no_inverse") or []))
    print(f"[inv] Data-driven inverse predicate ({dataset}）：{len(cycles)} Yes 2-loop,"
          f"Cover {n_inv}/{K} predicate ({n_inv/K*100:.1f}%）；"
          f"Symmetry class {len(d.get('symmetric') or [])} walking style(24), "
          f"undefined inverse {len(d.get('no_inverse') or [])} Go alone φ export")
    return groups


