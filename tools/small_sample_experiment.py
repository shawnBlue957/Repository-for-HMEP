def get_device(explicit: Optional[str] = None) -> torch.device:
    """Parse the running device. The entire code is followed by `device=tensor.device`, so migration only requires moving the entry tensor.

    ⚠️ CLIP feature extraction (object cropping/whole image) uses `clip_cpu.py`, **always on the CPU**:
    This module is rebuilt according to the torch CPU version, and the CLIP weight is fp16, and the benefits are limited on 3060
    And transportation costs are high. Therefore, this switch only accelerates **training and evaluation**, and feature extraction is still CPU (one-time, cacheable).
    """
    global _DEVICE
    if _DEVICE is not None:
        return _DEVICE
    if explicit:
        dev = torch.device(explicit)
    elif torch.cuda.is_available():
        dev = torch.device("cuda")
    else:
        dev = torch.device("cpu")
    _DEVICE = dev
    return dev


def load_semantic(use_clip_text: bool, sem_file: str = "semantic_path.pt"):
    """Load the CLIP semantic path tensor (Equation 15/23).

    `--use-clip-text` returns None when turned off, at which point v_txt/v_inv degenerates to random initialization
    (That is, according to the caliber of the previous round of experiments, M_inv has no semantics and the category layer must not be able to measure the effect).

    ⚠️ Caches are keyed by **filename**: `semantic_path.pt` for VG, `vrd_semantic.pt` for VRD,
    The shapes are different ((50,512) vs (70,512), (151,512) vs (101,512)).
    If you continue to use a single global variable, after running VRD and then returning to VG, you will get the tensor of another data set silently.
    """
    global _SEM
    if not use_clip_text:
        return None
    if _SEM is None or _SEM.get("__file__") != sem_file:
        path = os.path.join(ART, sem_file)
        if not os.path.exists(path):
            hint = ("python tools/build_vrd_semantic.py"
                    if "vrd" in sem_file else "python tools/build_semantic_path.py")
            raise SystemExit(f"missing artifacts/{sem_file} —— Please run first:\n  {hint}")
        d = torch.load(path, weights_only=False)
        d["__file__"] = sem_file
        _SEM = d
        # Record **0-based predicate name table** (length K, excluding background),
        # Provide involution projection (--use-adjoint) to map semantic group names to predicate subscripts.
        # ⚠️ `predicates_1b` is a ”1-based table with background” in the VG version.
        # The VRD version is a ”0-based table with the background stripped off” - the caliber is different.
        # Therefore, judge ”whether the first item looks like background” to avoid making the same mistake again.
        _p = None
        if "predicates_1b" in d:
            _p = list(d["predicates_1b"])
            if _p and str(_p[0]).lower().startswith("__"):
                _p = _p[1:]
        elif "predicates" in d:
            _p = list(d["predicates"])
        _SEM_NAMES[sem_file] = _p if _p else []
    return _SEM


