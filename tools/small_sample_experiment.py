class ImageDir:
    """Read the images in the **directory** by name (for VRD; the interface is consistent with `ImageZip.read`).

    In this way, the feature extraction code `extract_features` does not need to distinguish the data source - it only calls `read(name)`
    Take the raw bytes.
    """

    def __init__(self, dirs: Sequence[str]):
        self.dirs = [d for d in dirs if d and os.path.isdir(d)]
        if not self.dirs:
            raise FileNotFoundError(f"Image directory does not exist:{dirs}")
        self.index: Dict[str, str] = {}
        for d in self.dirs:
            for nm in os.listdir(d):
                if nm.lower().endswith((".jpg", ".jpeg", ".png", ".gif")):
                    self.index.setdefault(nm, os.path.join(d, nm))
                    base = os.path.splitext(nm)[0]
                    self.index.setdefault(base, os.path.join(d, nm))

    def read(self, name: str) -> Optional[bytes]:
        p = self.index.get(name) or self.index.get(os.path.basename(str(name)))
        if p is None or not os.path.exists(p):
            return None
        with open(p, "rb") as f:
            return f.read()

    def __len__(self) -> int:
        return len(self.index)


