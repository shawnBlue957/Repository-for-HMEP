def build_split(records: List[dict], cache: Dict[str, dict], K: int,
                nmax_cap: int = 80, pmax_cap: int = 64,
                strict: bool = True, inv_of: Optional[np.ndarray] = None,
                rev_mode: str = "legacy", mu_present: float = 1.0,
                mu_absent: float = 0.0, prior_mode: str = "none",
                _rev_reliability: Optional[dict] = None,
                _cooc: Optional[np.ndarray] = None,
                _cooc_total: Optional[np.ndarray] = None,
                cooc_temp: float = 1.0) -> SplitData:
    """Assembling tensor batches.

    ⚠️ `nmax_cap` / `pmax_cap` will **silently truncate** relationships that exceed the upper limit.
    Distribution of measured VG150: val 5,000 pictures P_max=150, test 26,446 pictures P_max=77,
    Therefore, the default value of 64 will lose **2.08% of the relationship** (6 pictures) on val, which is unacceptable in large sample experiments.
    When `strict=True` is used, an error will be thrown directly for any truncation to avoid mistaking ”missing data” for ”the model is not good”.

    ---------- Formula (8) Reverse weak label: three calibers of `rev_mode` ----------
    `legacy` (default, = original formula (8) caliber of the paper):
        With inverse annotation ⟹ y_tilde_ji = the inverse annotation, μ=1; otherwise y_tilde_ji = p itself, μ=0.2.
        **Actually measured, this caliber is harmful**: D arm with single head + BASE on VRD vs I arm without reverse supervision,
        mR@50 −0.0043 (t=−15.04), BRC@1 −0.0119 (t=−4.38).
        Root cause (VRD train actual measurement, 9,588 items with reverse annotation):
          The reverse label is consistent with the reverse predicate table **0.3%**
          The reverse label is inconsistent with the reverse predicate table **42.2%** (false reciprocity)
          The predicate itself has no defined inverse **57.5%**
        That is, the model is asked to fit 42% of the **wrong** reverse targets.
    `sym_check`: Only ”reverse annotation == the logical inverse of p” has μ=1, and the rest μ=0 (false reciprocities are discarded).
    `stats`: Give μ according to the **measured consistency rate** of each predicate (need to cooperate with `_rev_reliability`).
    """
    recs = [r for r in records if r.image_id in cache]
    max_n = max(len(r.labels) for r in recs)
    max_p = max((len(r.relations) for r in recs), default=1)
    if strict and max_n > nmax_cap:
        raise ValueError(f"N upper limit {nmax_cap} < Actual maximum number of objects {max_n}；"
                         f"Please increase nmax_cap (Otherwise the object will be silently discarded)")
    if strict and max_p > pmax_cap:
        raise ValueError(f"P upper limit {pmax_cap} < actual maximum relationship number {max_p}；"
                         f"Please increase pmax_cap (Otherwise, the relationship will be silently discarded)")
    N_max = max(1, min(nmax_cap, max_n))
    P_max = max(1, min(pmax_cap, max_p))

    d = SplitData(ids=[], N_max=N_max, P_max=P_max, v=[], t=[], s=[], masks=[],
                  sidx=[], oidx=[], ylab=[], ytil=[], mu=[], pmask=[], npairs=[], rels=[], n_obj=[])
    n_align_drop = 0
    for r in recs:
        c = cache[r.image_id]
        # ⚠️ The **object order of cache (ROI features) and annotation (triples) must be consistent**, otherwise the relationship index will point to the wrong object.
        # When the two are generated by different scripts, there may be a difference of 1~several objects (for example, the object filtering calibers of GQA and GQA-LT are different),
        # Do a prefix consistency check here: if inconsistent, the entire image will be discarded instead of silently misaligned.
        nc = int(c["v"].shape[0])
        n = min(len(r.labels), N_max, nc)
        if len(r.labels) != nc:
            mis = 0
            for j in range(min(n, len(r.boxes), len(c["boxes"]))):
                if (abs(float(r.boxes[j][0]) - float(c["boxes"][j][0])) > 1.0
                        or abs(float(r.boxes[j][1]) - float(c["boxes"][j][1])) > 1.0):
                    mis += 1
                    break
            if mis:
                n_align_drop += 1
                continue
        vv = torch.zeros(N_max, FEAT_DIM)
        vv[:n] = c["v"][:n]
        tt = torch.zeros(N_max, dtype=torch.long)
        tt[:n] = torch.tensor(c["labels"][:n], dtype=torch.long)
        ss = torch.zeros(N_max, GEOM_DIM)
        for j in range(n):
            ss[j] = torch.from_numpy(geom_features(c["boxes"][j], c["W"], c["H"]))
        mk = torch.zeros(3, N_max)
        mk[:, :n] = 1.0

        direct = {}
        rels_kept = []
        for rel in r.relations:
            if rel.subject < n and rel.object < n:
                direct[(rel.subject, rel.object)] = rel.predicate
        for rel in r.relations:
            if rel.subject < n and rel.object < n and len(rels_kept) < P_max:
                rels_kept.append((rel.subject, rel.object, rel.predicate - 1))

        sidx = torch.zeros(P_max, dtype=torch.long)
        oidx = torch.zeros(P_max, dtype=torch.long)
        ylab = torch.zeros(P_max, dtype=torch.long)
        ytil = torch.zeros(P_max, K)
        mu = torch.zeros(P_max)
        pmask = torch.zeros(P_max)
        for j, (s_, o_, p_) in enumerate(rels_kept):
            sidx[j], oidx[j], ylab[j] = s_, o_, p_
            rev = direct.get((o_, s_))
            if rev_mode == "legacy":
                # Original formula (8) of the paper Caliber: Maintain bit-by-bit reproduction (all existing results are based on this)
                if rev is not None:
                    ytil[j, rev - 1] = 1.0
                    mu[j] = mu_present
                else:
                    ytil[j, p_] = 1.0
                    mu[j] = 0.2 if mu_absent == 0.0 else mu_absent
                pmask[j] = 1.0
                continue
            # ---------- Correction: Credibility-weighted reverse weak label ----------
            # The measured old caliber is harmful (VRD: D vs I’s mR@50 −0.0043, t=−15.04),
            # The root cause is ”there is a reverse annotation” does not imply ”the reverse annotation is the logical inverse of p”:
            # VRD train Among the 9,588 items with reverse annotation, only 0.3% are consistent and 42.2% are inconsistent.
            # This predicate has no defined inverse 57.5%. The old caliber treated 42% of the **wrong** targets as credible oversight.
            ytil[j, p_] = 1.0
            inv_p = inv_of[p_] if (inv_of is not None and p_ < len(inv_of)) else -1
            if rev_mode == "cooc":
                # ---------- Co-occurrence statistics substitution: P(K | p, reverse pair) ----------
                # Motivation (VRD train actual measurement, correct reverse target is given on 9,588 reverse-labeled samples):
                # Formula (8) original 3.5% / theoretical inverse argmax 3.5% / CLIP text similarity 12.2%
                # **Co-occurrence statistics top-1 50.1%** (14 times higher)
                # Advantages: Only the training set **overall** statistics are needed, and it does not rely on the credibility of a single annotation.
                # Therefore, it can cover 68.4% of the samples without reverse annotation (Formula (8) can only be used there
                # Harmful ”reflexive weak tags”).
                if _cooc is None or _cooc_total is None:
                    ytil[j, p_] = 0.0
                    mu[j] = 0.0
                else:
                    row = _cooc[p_].astype(np.float64)
                    s = float(_cooc_total[p_])
                    if s <= 0:
                        ytil[j, p_] = 0.0
                        mu[j] = 0.0
                    else:
                        prob = row / row.sum()
                        # μ = The proportion of the predicate ”having reverse co-occurrence” (sample support),
                        # Then soften the distribution according to temperature; if there is no co-occurrence, μ=0
                        supp = float(row.sum() / max(_cooc_total[p_], 1.0))
                        ytil[j] = torch.from_numpy(
                            (prob ** (1.0 / max(cooc_temp, 1e-6))).astype(np.float32))
                        mu[j] = mu_present * supp
            elif rev is None:
                # No reverse annotation: The old implementation uses ”reflexive” weak labels (μ=0.2), which is also harmful in actual measurements——
                # It requires that p_ji has mass in p itself, and the reverse pair of real predicates is often of another class.
                ytil[j, p_] = 0.0
                mu[j] = mu_absent
            elif inv_p >= 0 and (rev - 1) == inv_p:
                ytil[j, inv_p] = 1.0          # Consistent ⟹ Trusted Oversight
                mu[j] = mu_present
            else:
                # False reciprocity ⟹ Discard the supervision (sym_check) or give μ (stats) according to the measured consistency rate
                ytil[j, inv_p if inv_p >= 0 else p_] = 1.0
                mu[j] = (_rev_reliability or {}).get(p_, 0.0) \
                    if prior_mode == "stats" else 0.0
            pmask[j] = 1.0

        d.ids.append(r.image_id); d.v.append(vv); d.t.append(tt); d.s.append(ss)
        d.masks.append(mk); d.sidx.append(sidx); d.oidx.append(oidx); d.ylab.append(ylab)
        d.ytil.append(ytil); d.mu.append(mu); d.pmask.append(pmask)
        d.npairs.append(len(rels_kept)); d.rels.append(rels_kept); d.n_obj.append(n)
    if n_align_drop:
        print(f"  ⚠ cache/The order of labeled objects is inconsistent and discarded. {n_align_drop} Graph (avoiding relationship index misalignment)")
    return d


def _module_device(m: nn.Module) -> Optional[torch.device]:
    """Get the device where the module is located: first look at the parameters, then the buffer (FrozenObjText only has buffer)."""
    for p in m.parameters():
        return p.device
    for b in m.buffers():
        return b.device
    return None


def make_batch(data: SplitData, idx: List[int], obj_emb: Optional[nn.Module] = None) -> dict:
    xv = torch.stack([data.v[i] for i in idx])
    xt = torch.stack([data.t[i] for i in idx])
    if obj_emb is not None:
        # ⚠️ `data.t` is resident in CPU, while obj_emb may be on GPU.
        # `nn.Embedding` goes to `F.embedding`, **requires the index and weight to be on the same device** (otherwise it will report
        # "index is on cpu, different from other tensors on cuda:0"); 
        # And the advanced indexing used by `FrozenObjText` happens to allow CPU indexing ⟹ Only the Embedding path will explode.
        dev_e = _module_device(obj_emb)
        if dev_e is not None and dev_e != xt.device:
            xt = xt.to(dev_e)
        xt = obj_emb(xt)
    xs = torch.stack([data.s[i] for i in idx])
    return {
        "x": {"v": xv, "t": xt, "s": xs},
        "masks": torch.stack([data.masks[i] for i in idx]),
        "s_idx": torch.stack([data.sidx[i] for i in idx]),
        "o_idx": torch.stack([data.oidx[i] for i in idx]),
        "y_label": torch.stack([data.ylab[i] for i in idx]),
        "y_tilde": torch.stack([data.ytil[i] for i in idx]),
        "mu": torch.stack([data.mu[i] for i in idx]),
        "pmask": torch.stack([data.pmask[i] for i in idx]),
    }


