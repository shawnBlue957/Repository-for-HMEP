def build_inv_idx(pred_names) -> np.ndarray:
    """List of predicate names (index 0 = background) → inverse predicate index array; -1 if there is no inverse.

    caliber: **position** = 1-based predicate number (subscript of `pred_names`),
    **value** = **0-based** index of the logical inverse; read side `rp = int(inv_idx[p+1]) - 1`.
    ⚠️Early versions also saved the **value** as `pred_names.index(q)` (1-based position),
    The reading end is then subtracted by 1 ⟹ **The overall offset is one bit**, and the actual measurement result is
    `above → using`, `behind → laying on`, `covering → covering` (self-referential)
    etc. Totally wrong mapping. The two calibers must be clearly distinguished.

    The data source uses group-to-group `VG_INV_GROUPS`: members in the group point to the opposite **group head**,
    Therefore, ”many to one”; symmetry only requires that **group head ↔ group head** be consistent in both directions.
    """
    inv = np.full(len(pred_names), -1, dtype=int)
    for grp_a, grp_b in VG_INV_GROUPS:
        for A, B in ((grp_a, grp_b), (grp_b, grp_a)):
            if not A or not B or A[0] not in pred_names or B[0] not in pred_names:
                continue
            # ⚠️ Save **0-based subscript** (the reading end will subtract 1 to restore it to 1-based predicate number)
            tgt = pred_names.index(B[0]) - 1
            for p in A:
                if p in pred_names:
                    inv[pred_names.index(p)] = tgt
    # ---------- Self-check: No self-reference is allowed; the group heads must be bidirectionally symmetrical ----------
    heads = set()
    for ga, gb in VG_INV_GROUPS:
        if ga and gb and ga[0] in pred_names and gb[0] in pred_names:
            heads.add((ga[0], gb[0]))
    for i in range(1, len(pred_names)):
        # ⚠️ The **value** of `inv` is a 0-based index, and the loop variable i is a 1-based position,
        # Therefore, self-referential judgment must compare inv[i] == i - 1.
        if inv[i] == i - 1:
            raise AssertionError(f"The inverse predicate table refers to itself:{pred_names[i]!r}")
        if inv[i] >= 0 and not (0 <= inv[i] < len(pred_names)):
            raise AssertionError(f"Inverse predicate range out of bounds:{pred_names[i]!r} -> {inv[i]}")
    for a, b in heads:
        ia, ib = pred_names.index(a), pred_names.index(b)
        # The value is a 0-based subscript, so the expected value is also -1
        if inv[ia] != ib - 1 or inv[ib] != ia - 1:
            raise AssertionError(
                f"The first part of the inverse predicate group is asymmetric:{a!r}->{pred_names[inv[ia]+1]!r} "
                f"(Expectation {b!r})，{b!r}->{pred_names[inv[ib]+1]!r} (Expectation {a!r})")
    # ---- Chain alignment self-test: σ² = id ----
    # The group-to-group mapping is ”many-to-one”: all members in the group point to the opposite **group head**, so the **group head** is required
    # σ²=id; for non-first members in the group, the correct property is ”σ² returns to the head of this group” (two-step convergence).
    # Example: over belongs to the ”above” family [above, over], σ(over)=under, σ(under)=above
    # —— Return to the head of this group above, which is a correct many-to-one chain, not an error.
    n_chain = 0
    group_of = {}
    for gi, (ga, gb) in enumerate(VG_INV_GROUPS):
        for p in (ga or []) + (gb or []):
            if p in pred_names:
                group_of[pred_names.index(p)] = (gi, p in (ga or []))
    for k in range(1, len(pred_names)):
        q = inv[k]
        if q < 0:
            continue
        back = inv[q + 1]                 # 0-based value of σ²
        back1 = back + 1                  # Convert to 1-based position for easy comparison
        if back1 == k:
            continue
        # Non-leader members: allow σ² to return to the leader of this group
        gk = group_of.get(k)
        if gk is not None:
            gi, is_head_member = gk
            ga, gb = VG_INV_GROUPS[gi]
            grp_head = (ga if is_head_member else gb)[0]
            if grp_head in pred_names and back1 == pred_names.index(grp_head):
                continue
        n_chain += 1
    if n_chain:
        raise AssertionError(
            f"The inverse predicate chain is not closed:{n_chain} predicate k→q→q' Never returned k, Nor did he return to the top of this group."
            f"Violation of involution axiom σ²=id.Check the deposit caliber (should be 0-based subscript)"
            f"with VG_INV_GROUPS Whether there is preemption.")
    return inv


def _new_acc(K: int) -> dict:
    """Evaluation accumulator. All quantities are additive and can be accumulated in chunks (see evaluate_streaming)."""
    return {"hit": {k: 0.0 for k in KS},
            "per_hit": {k: np.zeros(K) for k in KS},
            "per_cnt": np.zeros(K),
            "tot": 0.0, "top1": 0.0,
            "n_rel": 0, "n_img": 0,
            # --- Group B: Directional only ---
            # BRC: Bidirectional relationship classification. Taking ”unordered pairs” as a group, it is required to predict correctly in both directions**
            "brc_correct": 0.0, "brc_total": 0.0,
            # IR@K: Reciprocal recall. For the truth value r of (s,o), check the rank of its **logical inverse r’** on the inverse pair (o,s)
            "ir_hit": {k: 0.0 for k in KS},
            "ir_per_hit": {k: np.zeros(K) for k in KS},
            "ir_per_cnt": np.zeros(K),
            "ir_tot": 0.0, "n_inv_pred": 0}


@torch.no_grad()
def _score_image(model, obj_emb, data: SplitData, i: int, dev,
                 eval_mode: str = "predcls"):
    """Produce candidate scores and a list of candidate pairs for the i-th picture.

    **Two candidate set calibers (key, determine whether it can be compared with SOTA)**:
    - `predcls` (standard PredCls, consistent with Neural Motifs / RePEAT / Motifs series):
      Candidates = **all ordered object pairs** in the graph × K predicates. 12.3 objects ⟹ ~139 pairs, 6950 candidates.
    - `gtpairs` (early version of this implementation, **easier**):
      Candidates = **Only pairs of entities appearing in the annotation** × K predicates. The average is only 6.6 pairs, 330 candidates.
      ⟹ Selecting a predicate among only 6.6 candidate pairs, the task is greatly simplified and the **number will be significantly artificially high**.
    """
    if eval_mode == "gtpairs":
        pairs = [(s, o) for (s, o, _) in data.rels[i]]
    else:
        n = data.n_obj[i]
        pairs = [(a, b) for a in range(n) for b in range(n) if a != b]
    if not pairs:
        return None, []
    S = torch.tensor([p[0] for p in pairs], dtype=torch.long, device=dev).unsqueeze(0)
    O = torch.tensor([p[1] for p in pairs], dtype=torch.long, device=dev).unsqueeze(0)
    xt = obj_emb(data.t[i].unsqueeze(0).to(dev)) if obj_emb is not None else \
        data.t[i].unsqueeze(0).to(dev)
    x = {"v": data.v[i].unsqueeze(0).to(dev),
         "t": xt,
         "s": data.s[i].unsqueeze(0).to(dev)}
    masks = data.masks[i].unsqueeze(0).to(dev)
    p_ij, _ = model.forward_inference(x, masks, S, O)
    return p_ij[0], pairs


@torch.no_grad()
def _acc_chunk(model, obj_emb, data: SplitData, hp: HyperParams,
               prior, acc: dict,
               eval_mode: str = "predcls",
               inv_idx: Optional[np.ndarray] = None,
               pred_keep: Optional[torch.Tensor] = None,
               skip_preds: Optional[set] = None) -> None:
    """Accumulate the evaluation results of a SplitData tile into acc.

    `pred_keep`: Optional (K,) bool mask to only sort within this subset of predicates.
        Used for **cross-dataset zero-sample evaluation** (such as VRD→UnRel), or **discriminant view after excluding trivial predicates**
        (For example, GQA excludes left/right, see `--exclude-preds`).
        `None` = Full vocabulary sorting (strict caliber).
    `skip_preds`: An optional set of 0-based predicates. **Relationships in which these predicates appear in GT are not counted in the denominator**.
        Combined with `pred_keep`, the full scope of ”exclude X subset” can be obtained (not counting the GT of the predicate,
        Nor is it allowed to enter sorting).
    `prior`: plain (K,) array = frequency prior; **callable** when pressed
        `prior(data, i, cand_pairs) -> (n_pairs, K)` On-site output score,
        Used for model-free geometric baselines, etc.
    """
    if model is not None:
        model.eval()
    dev = next(model.parameters()).device if model is not None else torch.device("cpu")
    K = hp.K
    acc["n_img"] += len(data.ids)

    for i in range(len(data.ids)):
        gt = data.rels[i]                       # (s,o,pred0)
        if not gt:
            continue
        acc["n_rel"] += len(gt)

        if callable(prior):
            # Model-free baseline: produced by the caller (data, i, cand_pairs) on-site
            cand_pairs = ([(s2, o2) for (s2, o2, _) in gt] if eval_mode == "gtpairs"
                          else [(a, b) for a in range(data.n_obj[i])
                                for b in range(data.n_obj[i]) if a != b])
            if not cand_pairs:
                continue
            sc = np.asarray(prior(data, i, cand_pairs), dtype=np.float32)
            scores = torch.tensor(sc, dtype=torch.float32, device=dev)
        elif prior is not None:
            cand_pairs = ([(s2, o2) for (s2, o2, _) in gt] if eval_mode == "gtpairs"
                          else [(a, b) for a in range(data.n_obj[i])
                                for b in range(data.n_obj[i]) if a != b])
            scores = torch.tensor(np.tile(prior, (len(cand_pairs), 1)),
                                  dtype=torch.float32, device=dev)
        else:
            scores, cand_pairs = _score_image(model, obj_emb, data, i, dev,
                                              eval_mode=eval_mode)
            if scores is None:
                continue

        if pred_keep is not None:
            # Predicates outside the subset are pressed to -inf ⟹ Do not participate in ranking (target domain vocabulary limit / exclude trivial predicates)
            scores = scores.masked_fill(~pred_keep.unsqueeze(0).to(scores.device), -1e9)

        # 2026-10-21 Route B: pair-level presence calibration
        #   s_ij[k] = z_ij[k] + α · LSE(z_ij)
        # α=0 is equivalent to pure logits (per-pair normalization has been removed);
        # α=1 is equivalent to log-softmax (completely restores pair confidence);
        # 0<α<1 is a compromise: both retaining comparability across pairs, and taking advantage of ”how certain this pair is as a whole”.
        # LSE takes along the predicate dimension (dim=-1), gets a scalar for each pair, and then broadcasts back to (P,K).
        if SCORE_LSE_ALPHA > 0:
            _lse = torch.logsumexp(scores, dim=-1, keepdim=True)   # (P,1) free energy
            scores = scores + SCORE_LSE_ALPHA * _lse

        # 2026-10-21 Stage-2: **Internal reordering of pair** (really changing the order within pair)
        # learn - learning residual header (vrp.rerank.RelReranker), Δ differs per predicate
        # calib —— a priori calibration Δ_k = -τ·log π_k (long-tail logit adjustment, for comparison)
        if RERANKER is not None:
            from vrp.rerank import rerank_inplace as _rerank_inplace
            scores = _rerank_inplace(RERANKER, scores, data, i, RERANK_M_TOP,
                                     RERANK_TXT.to(scores.device), RERANK_INV)
        elif RERANK_CALIB is not None:
            scores = torch.log(scores.clamp_min(1e-9)) + RERANK_CALIB.to(scores.device)
        pair_pos = {p: k for k, p in enumerate(cand_pairs)}
        if RANK_SCOPE == "pair":
            _ord = torch.argsort(-scores, dim=-1, stable=True)      # (P,K)
            _rk = torch.empty_like(_ord)
            _rk.scatter_(1, _ord,
                         torch.arange(K, device=scores.device).expand_as(_ord))
            rank_of = _rk.reshape(-1)
        else:
            flat = scores.reshape(-1)               # Candidate = candidate pair × K predicate
            order = torch.argsort(-flat, stable=True)
            rank_of = torch.empty_like(order)
            rank_of[order] = torch.arange(len(order), device=order.device)
        for (s, o, p) in gt:
            if skip_preds and p in skip_preds:
                continue                        # The GT of the excluded predicate is not included in the denominator
            j = pair_pos.get((s, o))
            if j is None:
                continue                        # The truth value pair is not in the candidate set (only possible with gtpairs caliber)
            r = int(rank_of[j * K + p]) + 1
            acc["tot"] += 1
            for k in KS:
                if r <= k:
                    acc["hit"][k] += 1
                    acc["per_hit"][k][p] += 1
            acc["per_cnt"][p] += 1
            acc["top1"] += float(int(torch.argmax(scores[j])) == p)

        # ---------- Group B: Directional indicator (the pair that needs to be reversed is also in the candidate set ⟹ only predcls caliber) ----------
        if eval_mode != "predcls" or inv_idx is None:
            continue
        gt_map = {(s, o): p for (s, o, p) in gt}    # Get the first predicate of the same pair, consistent with build_split
        if skip_preds:
            gt_map = {k: v for k, v in gt_map.items() if v not in skip_preds}

        # BRC: Taking unordered pairs {a,b} as a group, it is required to predict correctly in both directions
        seen = set()
        for (s, o), p in gt_map.items():
            key = (min(s, o), max(s, o))
            if key in seen:
                continue
            seen.add(key)
            q = gt_map.get((o, s))
            if q is None:
                continue                            # Non-bidirectional pairs, not included in the BRC denominator
            js, jo = pair_pos.get((s, o)), pair_pos.get((o, s))
            if js is None or jo is None:
                continue
            acc["brc_total"] += 1
            if (int(torch.argmax(scores[js])) == p) and (int(torch.argmax(scores[jo])) == q):
                acc["brc_correct"] += 1

        # IR@K: The rank of the logical inverse r’ of the truth value r on the inversion pair (o,s)
        for (s, o), p in gt_map.items():
            rp = int(inv_idx[p + 1]) - 1            # inv_idx Create table based on 1-based predicate number and convert to 0-based
            if rp < 0:
                continue                            # The inverse of this predicate is not within VG-50 ⟹ Undecidable, not included in the denominator
            jo = pair_pos.get((o, s))
            if jo is None:
                continue
            rr = int(rank_of[jo * K + rp]) + 1
            acc["ir_tot"] += 1
            for k in KS:
                if rr <= k:
                    acc["ir_hit"][k] += 1
                    acc["ir_per_hit"][k][rp] += 1
            acc["ir_per_cnt"][rp] += 1


def _finalize(acc: dict) -> dict:
    hit, tot = acc["hit"], acc["tot"]
    present = acc["per_cnt"] > 0
    out = {
        "top1": round(acc["top1"] / max(tot, 1), 4),
        "n_gt_triplets": int(tot),
        "avg_rel_per_img": round(acc["n_rel"] / max(acc["n_img"], 1), 3),
        "n_pred_present": int(present.sum()),
    }
    for k in KS:
        out[f"R@{k}"] = round(hit[k] / max(tot, 1), 4)
        if present.any():
            v = acc["per_hit"][k][present] / acc["per_cnt"][present]
            out[f"mR@{k}"] = round(float(v.mean()), 4)
        else:
            out[f"mR@{k}"] = 0.0

    # ---------- Group B: Directional indicators ----------
    out["BRC@1"] = round(acc["brc_correct"] / max(acc["brc_total"], 1), 4)
    out["n_brc_pairs"] = int(acc["brc_total"])
    for k in KS:
        out[f"IR@{k}"] = round(acc["ir_hit"][k] / max(acc["ir_tot"], 1), 4)
    irp = acc["ir_per_cnt"] > 0
    out["MIR@50"] = (round(float((acc["ir_per_hit"][50][irp] / acc["ir_per_cnt"][irp]).mean()), 4)
                     if irp.any() else 0.0)
    out["n_ir_triples"] = int(acc["ir_tot"])
    out["n_ir_preds"] = int(irp.sum())
    return out


@torch.no_grad()
def evaluate(model, obj_emb, data: SplitData, hp: HyperParams,
             prior=None, eval_mode: str = "predcls",
             inv_idx: Optional[np.ndarray] = None,
             pred_keep: Optional[torch.Tensor] = None,
             skip_preds: Optional[set] = None) -> dict:
    acc = _new_acc(hp.K)
    _acc_chunk(model, obj_emb, data, hp, prior, acc, eval_mode=eval_mode,
               inv_idx=inv_idx, pred_keep=pred_keep, skip_preds=skip_preds)
    return _finalize(acc)


@torch.no_grad()
def evaluate_streaming(model, obj_emb, records: List, cache: Dict[str, dict], K: int,
                       hp: HyperParams, prior: Optional[np.ndarray] = None,
                       chunk: int = 2000, nmax: int = 80, pmax: int = 160,
                       eval_mode: str = "predcls",
                       inv_idx: Optional[np.ndarray] = None, log=print,
                       pred_keep: Optional[torch.Tensor] = None,
                       skip_preds: Optional[set] = None) -> dict:
    """Chunked streaming evaluation: assembly block by block → evaluation → release, the upper bound of memory is determined by `chunk`.

    ⚠️ Necessity: `SplitData` expands each image into a fixed-length tensor resident in memory
    (N_max×512 + P_max×K), 26,446 test sets occupy approximately 4 GB,
    And the available memory of this machine is only 4.6 GB. One-time assembly triggers a lot of page breaks.
    The accumulator design (`_new_acc`) ensures that the block results are **bit-wise equivalent** to the overall evaluation.
    """
    acc = _new_acc(K)
    recs = [r for r in records if r.image_id in cache]
    n_chunk = max(1, math.ceil(len(recs) / chunk))
    for ci in range(n_chunk):
        part = recs[ci * chunk:(ci + 1) * chunk]
        sd = build_split(part, cache, K, nmax, pmax, strict=False)  # Evaluate Side Heng legacy
        _acc_chunk(model, obj_emb, sd, hp, prior, acc, eval_mode=eval_mode,
                   inv_idx=inv_idx, pred_keep=pred_keep, skip_preds=skip_preds)
        del sd
        if ci % 4 == 0 or ci == n_chunk - 1:
            log(f"    Evaluation chunking {ci+1}/{n_chunk} (Covered {acc['n_img']:,}/{len(recs):,} Figure)")
    return _finalize(acc)


